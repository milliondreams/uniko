//! Topic detection (P6) — F40.
//!
//! Community detection on the Entity co-occurrence graph.  Two
//! entities are linked when they appear together in the same Message,
//! Chunk, Episode, Action, or Artifact (via `MENTIONS`).  Communities
//! of size ≥ 2 become Topic nodes; member entities are linked by
//! `BELONGS_TO`.
//!
//! Algorithm: weighted Label Propagation (LPA).  Each entity starts
//! in its own community; iteratively, every entity adopts the
//! highest-weighted community label among its neighbours, with ties
//! broken by the smaller label id for deterministic convergence.
//! Linear time per iteration; converges in 5–10 sweeps for graphs
//! up to ~10K entities — comfortably within the periodic worker
//! budget in spec Part VI.
//!
//! Louvain is available via `CALL uni.algo.louvain(...)` in uni-db
//! for very large graphs.  We keep LPA as the default because it
//! avoids materialising a graph projection and is dead simple to
//! reason about; swap in Louvain when the entity count grows past
//! ~50K.

// Rust guideline compliant

use std::collections::HashMap;

use serde::Serialize;
use uni_db::Value;
use uniko_store::schema::{edges, labels};
